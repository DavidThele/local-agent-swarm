import sys
import time
from pathlib import Path
from google.genai import types

from infrastructure.debugging import debug_print
from infrastructure.parser import parse_llm_output
from infrastructure.prompt_router import send_prompt, GEMINI_3_8_FLASH
from pipelines.performance_analyzer import snapshot_prompt_history

from .runtime import LOGS_DIR, GLOBAL_ROOT, REPO_ROOT

def load_macro_analyzer_prompt() -> str:
    global_path = GLOBAL_ROOT / "prompts" / "macro_analyzer_instructions.md"
    if global_path.exists():
        return global_path.read_text(encoding="utf-8")
    repo_path = REPO_ROOT / "prompts" / "macro_analyzer_instructions.md"
    return repo_path.read_text(encoding="utf-8")

def analyze_macro(prompt_file: Path, xml_output_file: Path, video_file: Path):
    debug_print(f"[MacroAnalyzer] Starting analysis for prompt: {prompt_file.name}, xml: {xml_output_file.name}", "info")
    if not prompt_file.exists() or not xml_output_file.exists():
        debug_print("[MacroAnalyzer] Missing prompt or xml logs. Skipping analysis.", "warning")
        return

    sys_prompt = load_macro_analyzer_prompt()
    original_prompt = prompt_file.read_text(encoding="utf-8")
    synthesized_xml = xml_output_file.read_text(encoding="utf-8")

    full_prompt = (
        f"{sys_prompt}\n\n"
        f"=== ORIGINAL PROMPT RECEIVED BY SYNTHESIZER ===\n{original_prompt}\n\n"
        f"=== XML ACTIONS GENERATED BY SYNTHESIZER ===\n{synthesized_xml}\n\n"
        "Watch the attached screen recording video of the execution and evaluate performance according to the instructions above."
    )

    media_files = []
    
    if video_file.exists() and video_file.stat().st_size > 100:
        debug_print(f"[MacroAnalyzer] Uploading screen recording {video_file.name} to Gemini...", "info")
        try:
            with open(video_file, "rb") as f:
                video_bytes = f.read()

            video_part = types.Part.from_bytes(
                data=video_bytes,
                mime_type="video/mp4"
            )
            media_files.append(video_part)
        except Exception as e:
            debug_print(f"[MacroAnalyzer] Failed to upload video: {e}", "error")

    debug_print("[MacroAnalyzer] Analyzing macro execution...", "info")
    
    result_text, _, _ = send_prompt(
        prompt_text=full_prompt,
        model=GEMINI_3_8_FLASH,
        media_files=media_files,
        print_cost=True
    )
    
    if not result_text.strip():
        debug_print("[MacroAnalyzer] Analysis failed: Model returned an empty response.", "error")
        return

    analyzer_output_dir = LOGS_DIR / "analyzer_output"
    analyzer_output_dir.mkdir(parents=True, exist_ok=True)
    with open(analyzer_output_dir / f"macro_analyzer_output_{time.strftime('%Y-%m-%d_%H-%M-%S')}.txt", "a", encoding="utf-8") as log_file:
        log_file.write(f"\n=== Analysis Result at {time.strftime('%Y-%m-%d %H:%M:%S')} ===\n")
        log_file.write(result_text + "\n")

    commands = parse_llm_output(result_text)
    
    # Extract Evaluation Report & Success Reasoning info
    eval_report = next((cmd for cmd in commands if cmd.command == "EvaluationReport"), None)
    success_reasoning = next((cmd for cmd in commands if cmd.command == "SuccessReasoning"), None)
    update_instructions = next((cmd for cmd in commands if cmd.command == "UpdateMacroInstructions"), None)

    is_success = False

    if eval_report:
        content = eval_report.content if isinstance(eval_report.content, dict) else {}
        
        user_prompt_intent = content.get("UserPromptIntent", "").strip()
        observed_execution = content.get("ObservedVideoExecution", "").strip()
        alignment_comparison = content.get("AlignmentComparison", "").strip()
        verdict_text = content.get("Verdict", "").strip()
        
        # Check status attribute on <Verdict> or check the text
        verdict_status = eval_report.attributes.get("status", "")
        if not verdict_status and isinstance(content.get("Verdict"), dict):
            verdict_status = content.get("Verdict", {}).get("@status", "")

        debug_print("=== MACRO EVALUATION REPORT ===", "info")
        if user_prompt_intent:
            debug_print(f"[UserPromptIntent]\n{user_prompt_intent}", "data")
        if observed_execution:
            debug_print(f"[ObservedVideoExecution]\n{observed_execution}", "data")
        if alignment_comparison:
            debug_print(f"[AlignmentComparison]\n{alignment_comparison}", "data")
        if verdict_text or verdict_status:
            status_label = f" (Status: {verdict_status})" if verdict_status else ""
            debug_print(f"[Verdict{status_label}]\n{verdict_text}", "data")

        if verdict_status.upper() == "SUCCESS" or "SUCCESS" in verdict_text.upper():
            is_success = True

    if success_reasoning:
        reasoning_text = success_reasoning.content if isinstance(success_reasoning.content, str) else str(success_reasoning.content).strip()
        debug_print(f"[SuccessReasoning]\n{reasoning_text}", "success")
        is_success = True

    # Handle update instructions if present
    if update_instructions:
        cmd = update_instructions
        if isinstance(cmd.content, dict):
            new_content = cmd.content.get("Content", "").strip()
            summary = cmd.content.get("Summary", "Updated macro_instructions.md")
        else:
            new_content = str(cmd.content).strip()
            summary = "Updated macro_instructions.md"

        if new_content:
            global_inst = GLOBAL_ROOT / "prompts" / "macro_instructions.md"
            repo_inst = REPO_ROOT / "prompts" / "macro_instructions.md"
            
            if global_inst.exists():
                global_inst.write_text(new_content + "\n", encoding="utf-8")
            if repo_inst.exists():
                repo_inst.write_text(new_content + "\n", encoding="utf-8")
            
            snapshot_prompt_history(new_content + "\n", summary, prefix="macro")
            debug_print(f"[MacroAnalyzer] Upgraded macro_instructions.md: {summary}", "success")
            return

    if is_success:
        debug_print("[MacroAnalyzer] Macro execution succeeded completely. No system prompt updates needed.", "success")
    else:
        debug_print("[MacroAnalyzer] Analysis returned without an <UpdateMacroInstructions> tag or explicit success verdict.", "warning")

if __name__ == "__main__":
    if len(sys.argv) == 4:
        analyze_macro(Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3]))